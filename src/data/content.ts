/** その干支に当たる生まれ年(新しい順に6つ) */
export function birthYears(branch: number, latest = 2025): number[] {
  const out: number[] = []
  for (let y = latest; out.length < 6; y--) if ((((y - 4) % 12) + 12) % 12 === branch) out.push(y)
  return out
}

