export function bank(lang: Lang) {
  return {
    relation: (r: Relation, variant: number): Fortune => {
      const list = RELATION_VARIANTS[r]
      return list[variant % list.length][lang]
    },
    /** n: 同じ五行の干支どうしで文が重ならないよう (支の番号 + 月) を渡す */
    focus: (fc: Focus, n: number) => {
      const x = FOCUS_TEXT[fc][lang]
      return { label: x.label, line: x.lines[n % x.lines.length] }
    },
    tenGod: (g: TenGod) => TEN_GOD_TEXT[g][lang],
    tenGodName: (g: TenGod) => (lang === 'ko' ? TEN_GOD_TEXT[g].ko.yomi : g),
    dayMaster: (stem: string) => DAY_MASTER[stem][lang],
  }
}
